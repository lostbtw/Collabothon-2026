#!/usr/bin/env node
// Generates src/api/types.gen.ts from ../contracts/schemas/*.schema.json, no dependencies (the subset the contracts use).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "..", "..", "contracts", "schemas");
const outFile = join(here, "..", "src", "api", "types.gen.ts");

const pascal = (s) => s.replace(/(^|[_-])(\w)/g, (_, __, c) => c.toUpperCase());

const RENAME = { event: "OrdoEvent", document: "OrdoDocument" }; // avoid shadowing the DOM Event and Document types
const typeName = (file) => RENAME[file] ?? pascal(file);
const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
const doc = (text, pad) => (text ? `${pad}/** ${String(text).replace(/\*\//g, "* /")} */\n` : "");

function refName(ref) {
  const [file, frag] = ref.split("#");
  if (frag && frag.startsWith("/$defs/")) return frag.slice("/$defs/".length);
  if (file) return typeName(file.replace(/^\.\//, "").replace(".schema.json", ""));
  throw new Error(`Unsupported $ref: ${ref}`);
}

function toTs(s, pad = "") {
  if (s.$ref) return refName(s.$ref);
  if (s.oneOf) return [...new Set(s.oneOf.map((x) => toTs(x, pad)))].join(" | ");
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (s.type) {
    case "string": return "string";
    case "number": case "integer": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": {
      const item = s.items ? toTs(s.items, pad) : "unknown";
      return /[|&]/.test(item) ? `Array<${item}>` : `${item}[]`;
    }
    case "object": {
      const props = s.properties ?? {};
      const required = new Set(s.required ?? []);
      const inner = pad + "  ";
      const lines = Object.entries(props).map(
        ([k, v]) => `${doc(v.description, inner)}${inner}${key(k)}${required.has(k) ? "" : "?"}: ${toTs(v, inner)};`,
      );
      const extra = s.additionalProperties;
      if (extra && typeof extra === "object") lines.push(`${inner}[key: string]: ${toTs(extra, inner)};`);
      else if (lines.length === 0) return "Record<string, unknown>";
      return `{\n${lines.join("\n")}\n${pad}}`;
    }
    default: return "unknown";
  }
}

const out = [
  "// GENERATED by scripts/gen-types.mjs from contracts/schemas. Do not edit by hand.",
  "// Regenerate with: npm run gen:types",
  "",
];
const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();
const common = JSON.parse(readFileSync(join(schemaDir, "common.schema.json"), "utf8"));
for (const [name, def] of Object.entries(common.$defs)) {
  out.push(`${doc(def.description, "")}export type ${name} = ${toTs(def)};`, "");
}
for (const f of files) {
  if (f === "common.schema.json") continue;
  const schema = JSON.parse(readFileSync(join(schemaDir, f), "utf8"));
  const name = typeName(f.replace(".schema.json", ""));
  out.push(`${doc(schema.description, "")}export type ${name} = ${toTs(schema)};`, "");
}
writeFileSync(outFile, out.join("\n"));
console.log(`gen-types: wrote ${files.length - 1} entity types + ${Object.keys(common.$defs).length} common types to src/api/types.gen.ts`);
